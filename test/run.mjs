async function testGapIsReported() {
  console.log('\ntest: a turn that cannot be written is reported in the ledger')
  const root = scenario('gap')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('f')

  // The ledger write fails for the first turn only, the way a full disk or a
  // lock held elsewhere would.
  const realWrite = $.fs.write
  let armed = true
  $.fs.write = async function (path, text) {
    if (armed && String(path).endsWith('.md')) {
      armed = false
      throw new Error('disk is full')
    }
    return realWrite(path, text)
  }

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    origin: { kind: 'composer' },
    message: { content: [{ type: 'text', text: 'This turn will not land' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'Lost answer', reason: 'answer' }, async () => undefined)

  const md = readdirSync(root.cwd).filter(function (n) { return n.endsWith('.md') })
  check('nothing was written for the failed turn', md.length, 0)

  await hooks['session.append']($, {
    door: 'prompt',
    origin: { kind: 'composer' },
    message: { content: [{ type: 'text', text: 'This one lands' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'And is recorded', reason: 'answer' }, async () => undefined)

  const text = readFileSync(join(root.cwd, today() + '-demo-tracedoc.md'), 'utf8').replace(STAMP, 'STAMP')
  const gapAt = text.indexOf('> ⚠ TraceDoc: ')
  check('the gap is marked in the ledger', gapAt > 0, true)
  check(
    'and it names what failed',
    text.slice(gapAt, gapAt + '> ⚠ TraceDoc: a turn went unrecorded — turn.complete failed at STAMP: disk is full'.length),
    '> ⚠ TraceDoc: a turn went unrecorded — turn.complete failed at STAMP: disk is full',
  )
  check('the lost turn is absent', text.indexOf('This turn will not land'), -1)
  check('the recorded turn is present', text.indexOf('**Answer:**\nAnd is recorded') > 0, true)

  // The turn that could not be written is absent from the lines too, and no
  // line stands in for it: a gap in the ledger is a gap here, not a placeholder.
  const lines = readFileSync(join(root.cwd, today() + '-demo-tracedoc.jsonl'), 'utf8')
    .split('\n')
    .filter(Boolean)
  check('jsonl holds only the turn that landed', lines.length, 1)
  check('and it is the one that landed', lines[0].indexOf('"question":"This one lands"') > 0, true)
}

// The shapes below are the ones a real session on this machine holds, which is
// what the origin rule is derived from — including the row that proved the rule
// wrong the first time: a finished background task arriving as a prompt.
async function testWhichRowsAreQuestions() {
  console.log('\ntest: which rows are questions')
  const root = scenario('doors')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('g')
  const row = (door, origin, text) => ({
    door,
    origin: origin === undefined ? undefined : { kind: origin },
    message: { role: 'user', content: [{ type: 'text', text }] },
  })
  const send = (r) => hooks['session.append']($, r, async () => undefined)

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  const complete = (answer) => hooks['turn.complete']($, { answer, reason: 'answer' }, async () => undefined)

  // Turn A: the queue record is written as the prompt is queued, so it comes
  // first, and the prompt row follows it when the turn starts.
  await send(row('queue', 'human', 'the real question'))
  await send(row('prompt', 'human', 'the real question'))
  await complete('the real answer')

  // Turn B: a slash command is a turn of its own -- its record, then its output.
  // The record is sent the way the live engine really sends it for a plugin
  // command the model executes: origin=composer, the person's own. Taking it on
  // origin is what 0.5.3 did, and this row is here to hold that shut. The
  // built-in below leads with <command-name> instead and carries no origin at
  // all; both are recognised by the wrapper that opens them.
  await send(row('command', 'composer', '<command-message>ai-tracedoc-mods:on</command-message>\n<command-name>/ai-tracedoc-mods:on</command-name>'))
  await send(row('command', 'engine', '<local-command-stdout>TraceDoc recording is on</local-command-stdout>'))
  await send(row('command', undefined, '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>'))
  await complete('Recorded.')

  // Turn C: the live spelling of the person's origin. The engine says
  // 'composer' where a transcript says 'human', so a rule that took only one of
  // the two would record nothing at all on the other.
  await send(row('prompt', 'composer', 'a composer prompt'))
  await complete('Taken too.')

  // Turn D: a question that quotes a command record. The ledger's reader pastes
  // entries into the chat, so a wrapper inside a question is ordinary -- only a
  // row that *opens* with one is a command's record. Refusing this one would be
  // the silent loss the status file exists to reveal.
  await send(row('prompt', 'composer', '这条还是被记了：\n<command-message>ai-tracedoc-mods:off</command-message>\n<command-name>/ai-tracedoc-mods:off</command-name>'))
  await complete('Because the wrapper holds the opening, not the text.')

  // A compaction continuation, the caveat around a command, and blocks that are
  // not the person speaking at all.
  await send(row('delivery', undefined, 'This session is being continued from a previous conversation'))
  await send(row('command', undefined, '<local-command-caveat>Caveat: the messages below were generated'))
  await send(row('response', 'model', 'Here is the answer'))
  await send(row('tool-result', 'tool', 'file contents'))

  // An engine-injected prompt: a finished background task comes down the
  // person's own door and names who wrote it in `origin` alone. Taking the door
  // by itself recorded this as a question somebody had asked.
  await send(row('prompt', 'task-notification', '<task-notification>a background command finished</task-notification>'))

  // Status is written on a turn boundary, so the rows above need one to be
  // counted; session.end writes it too and has no question left to flush.
  await hooks['session.end']($, { reason: 'exit' }, async () => undefined)

  const text = readFileSync(join(root.cwd, today() + '-demo-tracedoc.md'), 'utf8')
  check('the prompt is recorded', text.indexOf('the real question') > 0, true)
  check('the live spelling of the person is recorded too', text.indexOf('a composer prompt') > 0, true)
  check('the command record is not', text.indexOf('<command-name>/ai-tracedoc-mods:on</command-name>'), -1)
  check('the built-in command record is not', text.indexOf('<command-name>/model</command-name>'), -1)
  check('the command output is not', text.indexOf('<local-command-stdout>'), -1)
  check('the caveat is not', text.indexOf('<local-command-caveat>'), -1)
  check('a question quoting one still is', text.indexOf('<command-message>ai-tracedoc-mods:off</command-message>') > 0, true)
  check('the continuation is not', text.indexOf('This session is being continued'), -1)
  check('a response block is not', text.indexOf('Here is the answer'), -1)
  check('a tool result is not', text.indexOf('file contents'), -1)
  check('an engine-injected prompt is not', text.indexOf('<task-notification>'), -1)
  // Once as a Question, once in the session heading the first question titles.
  check('one Question line for the prompt', (text.match(/\*\*Question:\*\* \d{4}-\d{2}-\d{2} \d{2}:\d{2}\nthe real question/g) || []).length, 1)
  check('the heading titles the session with it', text.indexOf('· the real question\n') > 0, true)
  // The layout itself: a label is a label and carries no text of its own, so a
  // long question or answer can never be mistaken for part of the label line.
  const labelLines = text.split('\n').filter(function (line) { return line.indexOf('**Question:**') === 0 })
  check('every Question label is the time and nothing else', labelLines.every(function (line) {
    return /^\*\*Question:\*\*( \d{4}-\d{2}-\d{2} \d{2}:\d{2})?$/.test(line)
  }), true)
  const answerLabels = text.split('\n').filter(function (line) { return line.indexOf('**Answer:**') === 0 })
  check('every Answer label is the label alone', answerLabels.every(function (line) {
    return line === '**Answer:**'
  }), true)

  const status = JSON.parse(readFileSync(join(root.pluginRoot, '.tracedoc-mods-status.json'), 'utf8'))
  check('every row counted', status.counters.rowsNotRecorded, 9)
  // The command turn recorded nothing, and that is not a lost turn: the two are
  // counted apart, and only the second is bad news.
  check('the command turn is counted as one', status.counters.commandTurnsSkipped, 1)
  check('a command turn is not a missing question', status.counters.orphanAnswers, 0)
  check('the queue row is sampled', status.counters.doorSamples.queue, 'the real question')
  check('a prompt is never sampled', status.counters.doorSamples.prompt, undefined)
}

