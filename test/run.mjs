// Drives hooks/tracedoc.js against a fake `$` and asserts the ledger bytes.
//
//   node test/run.mjs hooks/tracedoc.js
//
// This is a format guard, not a plugin surface: the engine reads a plugin's
// .claude-plugin/, hooks/, commands/, agents/ and skills/, and nothing here.
// It exists because the ledger is a committed artefact that the 0.3.x build
// writes too, so the two must agree byte for byte -- and because every claim
// in README.md about gating, rolling and gap-reporting is checked here rather
// than asserted in prose. Needs Node, no dependencies.

import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, existsSync, statSync, readdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { pathToFileURL } from 'node:url'

const MODULE = process.argv[2]
if (!MODULE) {
  console.error('usage: node run.mjs <path/to/tracedoc.js>')
  process.exit(2)
}

// The manifest beside the module, so the version the module answers with can be
// held to the one the plugin declares.
const MANIFEST = join(dirname(MODULE), '..', '.claude-plugin', 'plugin.json')

let failures = 0
function check(label, actual, expected) {
  if (actual === expected) {
    console.log('  ok   ' + label)
    return
  }
  failures++
  console.log('  FAIL ' + label)
  console.log('    expected: ' + JSON.stringify(expected))
  console.log('    actual:   ' + JSON.stringify(actual))
}

function makeDollar(root, store) {
  const fsApi = {
    async stat(path) {
      try {
        const info = statSync(path)
        return { kind: info.isDirectory() ? 'dir' : 'file', size: info.size }
      } catch (err) {
        throw new Error('ENOENT: ' + path)
      }
    },
    async read(path) {
      return readFileSync(path, 'utf8')
    },
    async write(path, text) {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, text, 'utf8')
    },
    async list(dir) {
      return readdirSync(dir, { withFileTypes: true }).map(function (entry) {
        return { name: entry.name, kind: entry.isDirectory() ? 'dir' : 'file' }
      })
    },
  }
  return {
    fs: fsApi,
    store: {
      async get(key) {
        return store.get(key)
      },
      async set(key, value) {
        store.set(key, value)
      },
      async delete(key) {
        store.delete(key)
      },
    },
    session: {
      async id() {
        return root.sessionId
      },
      async root() {
        return root.cwd
      },
    },
    command: {
      async register(spec) {
        root.registered.push(spec)
        return { command: spec.name }
      },
    },
    plugin: { root: root.pluginRoot, name: root.pluginName },
  }
}

// A fresh module instance per scenario: the recorder keeps its session state at
// module scope, and a cache-busting query is enough to get a new one.
async function load(tag) {
  const url = pathToFileURL(MODULE).href + '?t=' + tag
  const mod = await import(url)
  const hooks = {}
  const catches = {}
  const matchers = {}
  // on(event, handler) and on(event, matcher, handler) are both real forms; the
  // first is `session.start`'s, the second `command.run`'s.
  function on(name, matcher, handler) {
    if (typeof matcher === 'function') {
      handler = matcher
      matcher = undefined
    }
    hooks[name] = handler
    matchers[name] = matcher
    return {
      catch(fn) {
        catches[name] = fn
        return this
      },
    }
  }
  mod.register(on)
  return { hooks, catches, matchers }
}

function pad2(n) {
  return (n < 10 ? '0' : '') + n
}
function today() {
  const d = new Date()
  return String(d.getFullYear()) + pad2(d.getMonth() + 1) + pad2(d.getDate())
}
function dayOnly() {
  const d = new Date()
  return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate())
}
const STAMP = /\d{4}-\d{2}-\d{2} \d{2}:\d{2}/g

const HEADER_V1 =
  '# demo · TraceDoc\n\n' +
  'This file is auto-generated by the ai-tracedoc plugin ' +
  'from Claude Code session transcripts. ' +
  'It has not been manually curated.\n\n'

function scenario(name) {
  const base = mkdtempSync(join(tmpdir(), 'tdm-'))
  const cwd = join(base, 'demo')
  const pluginRoot = join(base, 'plugin')
  mkdirSync(cwd, { recursive: true })
  mkdirSync(pluginRoot, { recursive: true })
  writeFileSync(join(cwd, '.tracedoc-on'), 'ai-tracedoc: recording enabled for this project\n')
  return { name, cwd, pluginRoot, store: new Map(), sessionId: 'sess-1', registered: [], pluginName: 'ai-tracedoc-mods' }
}

