// Drives hooks/tracedoc.js against a fake `$` and asserts the ledger bytes.
//
//   node test/run.mjs hooks/tracedoc.js
//
// This is a format guard, not a plugin surface: the engine reads a plugin's
// .claude-plugin/, hooks/, commands/, agents/ and skills/, and nothing here.
// It exists because the ledger is a committed artefact that the 0.3.x build
// writes too, so the two must agree byte for byte -- and because every claim
// in README.md about gating, rolling and gap-reporting is checked here rather
// than asserted in prose. Needs Node, no dependencies.

import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, existsSync, statSync, readdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { pathToFileURL } from 'node:url'

const MODULE = process.argv[2]
if (!MODULE) {
  console.error('usage: node run.mjs <path/to/tracedoc.js>')
  process.exit(2)
}

let failures = 0
function check(label, actual, expected) {
  if (actual === expected) {
    console.log('  ok   ' + label)
    return
  }
  failures++
  console.log('  FAIL ' + label)
  console.log('    expected: ' + JSON.stringify(expected))
  console.log('    actual:   ' + JSON.stringify(actual))
}

function makeDollar(root, store) {
  const fsApi = {
    async stat(path) {
      try {
        const info = statSync(path)
        return { kind: info.isDirectory() ? 'dir' : 'file', size: info.size }
      } catch (err) {
        throw new Error('ENOENT: ' + path)
      }
    },
    async read(path) {
      return readFileSync(path, 'utf8')
    },
    async write(path, text) {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, text, 'utf8')
    },
    async list(dir) {
      return readdirSync(dir, { withFileTypes: true }).map(function (entry) {
        return { name: entry.name, kind: entry.isDirectory() ? 'dir' : 'file' }
      })
    },
  }
  return {
    fs: fsApi,
    store: {
      async get(key) {
        return store.get(key)
      },
      async set(key, value) {
        store.set(key, value)
      },
      async delete(key) {
        store.delete(key)
      },
    },
    session: {
      async id() {
        return root.sessionId
      },
      async root() {
        return root.cwd
      },
    },
    plugin: { root: root.pluginRoot },
  }
}

// A fresh module instance per scenario: the recorder keeps its session state at
// module scope, and a cache-busting query is enough to get a new one.
async function load(tag) {
  const url = pathToFileURL(MODULE).href + '?t=' + tag
  const mod = await import(url)
  const hooks = {}
  const catches = {}
  function on(name, handler) {
    hooks[name] = handler
    return {
      catch(fn) {
        catches[name] = fn
        return this
      },
    }
  }
  mod.register(on)
  return { hooks, catches }
}

function pad2(n) {
  return (n < 10 ? '0' : '') + n
}
function today() {
  const d = new Date()
  return String(d.getFullYear()) + pad2(d.getMonth() + 1) + pad2(d.getDate())
}
function dayOnly() {
  const d = new Date()
  return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate())
}
const STAMP = /\d{4}-\d{2}-\d{2} \d{2}:\d{2}/g

const HEADER_V1 =
  '# demo · TraceDoc\n\n' +
  'This file is auto-generated by the ai-tracedoc plugin ' +
  'from Claude Code session transcripts. ' +
  'It has not been manually curated.\n\n'

function scenario(name) {
  const base = mkdtempSync(join(tmpdir(), 'tdm-'))
  const cwd = join(base, 'demo')
  const pluginRoot = join(base, 'plugin')
  mkdirSync(cwd, { recursive: true })
  mkdirSync(pluginRoot, { recursive: true })
  writeFileSync(join(cwd, '.tracedoc-on'), 'ai-tracedoc: recording enabled for this project\n')
  return { name, cwd, pluginRoot, store: new Map(), sessionId: 'sess-1' }
}

// ---------------------------------------------------------------------------

async function testFirstTurn() {
  console.log('\ntest: a fresh project, one turn')
  const root = scenario('first')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('a')

  await hooks['session.start']($, { cwd: root.cwd, surface: 'cli', isInteractive: true }, async () => undefined)
  await hooks['session.append']($, {
    agentId: null,
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'What is 2+2?' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: '4', reason: 'answer', isAborted: false }, async () => undefined)

  const ledger = join(root.cwd, today() + '-demo-tracedocmod.md')
  if (!existsSync(ledger)) {
    failures++
    console.log('  FAIL ledger was not created at ' + ledger)
    return
  }
  const actual = readFileSync(ledger, 'utf8').replace(STAMP, 'STAMP')
  const expected =
    HEADER_V1 +
    '\n## ' + dayOnly() + ' · What is 2+2?\n\n<!-- session: sess-1 -->\n\n' +
    '**Question:** STAMP · What is 2+2?\n' +
    '\n' +
    '\n**Answer:** 4\n' +
    '\n'
  check('ledger bytes', actual, expected)

  const status = JSON.parse(readFileSync(join(root.pluginRoot, '.tracedoc-mods-status.json'), 'utf8'))
  check('counters.recorded', status.counters.recorded, 1)
  check('counters.turns', status.counters.turns, 1)
  check('counters.orphanAnswers', status.counters.orphanAnswers, 0)
  check('doors seen', JSON.stringify(status.counters.appendsByDoor), '{"prompt":1}')
}

async function testSecondTurn() {
  console.log('\ntest: a second turn in the same session')
  const root = scenario('second')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('b')

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'First question' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'First answer', reason: 'answer' }, async () => undefined)

  const before = readFileSync(join(root.cwd, today() + '-demo-tracedocmod.md'), 'utf8')

  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'Second question' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'Second answer', reason: 'answer' }, async () => undefined)

  const after = readFileSync(join(root.cwd, today() + '-demo-tracedocmod.md'), 'utf8')
  const delta = after.slice(before.length).replace(STAMP, 'STAMP')
  check(
    'byte delta of the second turn carries no new session heading',
    delta,
    '**Question:** STAMP · Second question\n\n\n**Answer:** Second answer\n\n',
  )
  check('only one volume on disk', readdirSync(root.cwd).filter(function (n) { return n.endsWith('.md') }).length, 1)
}

async function testMarkerAbsent() {
  console.log('\ntest: no .tracedoc-on means nothing is written')
  const root = scenario('off')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('c')

  const marker = join(root.cwd, '.tracedoc-on')
  const { rmSync } = await import('node:fs')
  rmSync(marker)

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'Should not be recorded' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'Nor this', reason: 'answer' }, async () => undefined)

  const md = readdirSync(root.cwd).filter(function (n) { return n.endsWith('.md') })
  check('no ledger written', md.length, 0)
  const status = JSON.parse(readFileSync(join(root.pluginRoot, '.tracedoc-mods-status.json'), 'utf8'))
  check('counters.skippedDisabled', status.counters.skippedDisabled, 1)
  check('counters.recorded', status.counters.recorded, 0)
}

async function testVolumeRoll() {
  console.log('\ntest: a new session arriving at an over-threshold volume rolls it')
  const root = scenario('roll')
  const $ = makeDollar(root, root.store)

  // A volume already past the 200 KiB threshold, written by a previous session.
  const v1 = join(root.cwd, today() + '-demo-tracedocmod.md')
  writeFileSync(v1, HEADER_V1 + '\n## 2026-01-01 · old\n\n<!-- session: older -->\n\n' + 'x'.repeat(210 * 1024) + '\n')

  const { hooks } = await load('d')
  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'A new session begins' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'In a new volume', reason: 'answer' }, async () => undefined)

  const v2name = today() + '-demo-tracedocmod-02.md'
  const v2 = join(root.cwd, v2name)
  if (!existsSync(v2)) {
    failures++
    console.log('  FAIL volume 2 was not created; saw ' + JSON.stringify(readdirSync(root.cwd)))
    return
  }
  const v2text = readFileSync(v2, 'utf8')
  check(
    'volume 2 header',
    v2text.slice(0, v2text.indexOf('\n## ')),
    '# demo · TraceDoc (Volume 2)\n\nContinued from: [' + today() + '-demo-tracedocmod.md](./' + today() + '-demo-tracedocmod.md)\n\n',
  )
  const v1text = readFileSync(v1, 'utf8')
  check(
    'volume 1 footer',
    v1text.slice(-('\n\n---\n\nContinued in: [' + v2name + '](./' + v2name + ')\n').length),
    '\n\n---\n\nContinued in: [' + v2name + '](./' + v2name + ')\n',
  )
}

async function testDeferredQuestion() {
  console.log('\ntest: a question the module never paired (session.end flushes it)')
  const root = scenario('flush')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('e')

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'Asked but unanswered' }] },
  }, async () => undefined)
  await hooks['session.end']($, { reason: 'exit', sessionId: 'sess-1' }, async () => undefined)

  const text = readFileSync(join(root.cwd, today() + '-demo-tracedocmod.md'), 'utf8').replace(STAMP, 'STAMP')
  check('question-only entry, no Answer line', text.indexOf('**Answer:**'), -1)
  check('ends question-only', text.endsWith('**Question:** STAMP · Asked but unanswered\n\n'), true)
}

async function testGapIsReported() {
  console.log('\ntest: a turn that cannot be written is reported in the ledger')
  const root = scenario('gap')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('f')

  // The ledger write fails for the first turn only, the way a full disk or a
  // lock held elsewhere would.
  const realWrite = $.fs.write
  let armed = true
  $.fs.write = async function (path, text) {
    if (armed && String(path).endsWith('.md')) {
      armed = false
      throw new Error('disk is full')
    }
    return realWrite(path, text)
  }

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'This turn will not land' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'Lost answer', reason: 'answer' }, async () => undefined)

  const md = readdirSync(root.cwd).filter(function (n) { return n.endsWith('.md') })
  check('nothing was written for the failed turn', md.length, 0)

  await hooks['session.append']($, {
    door: 'prompt',
    message: { content: [{ type: 'text', text: 'This one lands' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'And is recorded', reason: 'answer' }, async () => undefined)

  const text = readFileSync(join(root.cwd, today() + '-demo-tracedocmod.md'), 'utf8').replace(STAMP, 'STAMP')
  const gapAt = text.indexOf('> ⚠ TraceDoc: ')
  check('the gap is marked in the ledger', gapAt > 0, true)
  check(
    'and it names what failed',
    text.slice(gapAt, gapAt + '> ⚠ TraceDoc: a turn went unrecorded — turn.complete failed at STAMP: disk is full'.length),
    '> ⚠ TraceDoc: a turn went unrecorded — turn.complete failed at STAMP: disk is full',
  )
  check('the lost turn is absent', text.indexOf('This turn will not land'), -1)
  check('the recorded turn is present', text.indexOf('**Answer:** And is recorded') > 0, true)
}

async function testUnexaminedDoors() {
  console.log('\ntest: doors that are not questions are counted, sampled and not recorded')
  const root = scenario('doors')
  const $ = makeDollar(root, root.store)
  const { hooks } = await load('g')

  await hooks['session.start']($, { cwd: root.cwd }, async () => undefined)
  await hooks['session.append']($, {
    door: 'command',
    origin: { kind: 'human' },
    message: { role: 'user', content: [{ type: 'text', text: '/ai-tracedoc-mods:on and its output row' }] },
  }, async () => undefined)
  await hooks['session.append']($, {
    door: 'queue',
    origin: { kind: 'human' },
    message: { role: 'user', content: [{ type: 'text', text: '/ai-tracedoc-mods:on and its output row' }] },
  }, async () => undefined)
  await hooks['session.append']($, {
    door: 'prompt',
    origin: { kind: 'human' },
    message: { role: 'user', content: [{ type: 'text', text: 'the real question' }] },
  }, async () => undefined)
  await hooks['turn.complete']($, { answer: 'the real answer', reason: 'answer' }, async () => undefined)

  const text = readFileSync(join(root.cwd, today() + '-demo-tracedocmod.md'), 'utf8')
  check('a command row is not in the ledger', text.indexOf('/ai-tracedoc-mods:on'), -1)
  check('the prompt row is', text.indexOf('the real question') > 0, true)

  const status = JSON.parse(readFileSync(join(root.pluginRoot, '.tracedoc-mods-status.json'), 'utf8'))
  check('every door counted', JSON.stringify(status.counters.appendsByDoor), '{"command":1,"queue":1,"prompt":1}')
  check(
    'shapes recorded',
    Object.keys(status.counters.appendShapes).sort().join(' ; '),
    'command | role=user | isMeta=undefined | origin=human ; prompt | role=user | isMeta=undefined | origin=human ; queue | role=user | isMeta=undefined | origin=human',
  )
  check('the command row is sampled', status.counters.doorSamples.command, '/ai-tracedoc-mods:on and its output row')
  check('the queue row is sampled', status.counters.doorSamples.queue, '/ai-tracedoc-mods:on and its output row')
  check('a prompt is not sampled', status.counters.doorSamples.prompt, undefined)
}

